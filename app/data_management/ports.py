from typing import Protocol, List, Dict, Any, Optional, Tuple
from datetime import date

class function_ports(Protocol):
    """Repository 端口接口，定义数据访问层的所有操作"""
    

    def create_table(self) -> None: ...
    

    def add_user(self, user_id: str) -> None: ...
    def search_user(self, user_id: str) -> Optional[Dict[str, Any]]: ...
    def add_fund(self, user_id: str, fund: int) -> None: ...


    def add_cards(self, cards: List[Tuple]) -> None: ...
    def search_card(self, card_id: int, user_id: str) -> Optional[Dict[str, Any]]: ...
    def search_card_last(self, user_id: str) -> Optional[Dict[str, Any]]: ...
    def search_cards(self, user_id: str) -> List[Dict[str, Any]]: ...
    def set_card_user(self, new_card_id: int, new_user_id: str, 
                      card_id: int, user_id: str) -> None: ...
    def delete_cards(self, cards: List[Tuple[int, str]]) -> None: ...
    

    def add_slots(self, slots: List[Tuple[str, int]]) -> None: ...
    def search_slots(self, user_id: str) -> List[Dict[str, Any]]: ...
    def delete_slots(self, slots: List[Tuple[str, int]]) -> None: ...
    

    def add_event(self, event_id: str, timestamp: int) -> None: ...
    def search_event(self, event_id: str) -> Optional[Dict[str, Any]]: ...
    def delete_events(self, timestamp: int) -> None: ...
    

    def add_sign_in(self, user_id: str, date: str, timestamp: int) -> None: ...
    def search_sign_in(self, user_id: str) -> Optional[Dict[str, Any]]: ...
    def update_sign_in_date(self, user_id: str, date: str, 
                           past_date: str, timestamp: int) -> None: ...
    def update_sign_in_count(self, user_id: str, timestamp: int) -> None: ...
    
